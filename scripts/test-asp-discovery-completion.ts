import assert from 'node:assert/strict';
import {unfinishedReplyProblem,requestsSavingOptions} from '../src/server/advice/replyCompletion.js';
const url='https://www.nordea.fi/en/personal/our-services/savings-investments/savings-accounts/asp-account.html';
const prose='ASP is a separate first-home savings account. '.repeat(11);
assert.equal(unfinishedReplyProblem(prose+'\nSource: '+url,[url]),null);
assert.equal(unfinishedReplyProblem(prose+'\n'+url,[url]),null);
assert.ok(unfinishedReplyProblem(prose+'\nSource: https://unverified.invalid/rule',[url]));
assert.ok(unfinishedReplyProblem(prose+'It depends on the\nSource: '+url,[url]));
assert.ok(unfinishedReplyProblem(prose+"I can help you with the plan's\nSource: "+url,[url]));
assert.ok(unfinishedReplyProblem(prose+'\nSource: '+url));
assert.ok(unfinishedReplyProblem(prose+'It would help estimate the 1',[url]));
assert.equal(unfinishedReplyProblem('Could you tell me your saving goal?',[url]),null);
assert.equal(unfinishedReplyProblem(prose+'Complete thought.',[url]),null);
const exact="1. My partner and I are hoping to buy our first home. I'm saving a little every month, but I don't know the best way to go about it. What would you suggest?";
assert.equal(unfinishedReplyProblem(prose+'\nSource: [Nordea]('+url+')',[url]),null);
assert.equal(unfinishedReplyProblem(prose+'\nSource: '+url+'\n'+url,[url]),null);
assert.equal(unfinishedReplyProblem(prose+'\nSource: <'+url+'>',[url]),null);
assert.equal(unfinishedReplyProblem(prose+' (see '+url+')',[url]),null);
assert.ok(requestsSavingOptions(exact));
assert.ok(requestsSavingOptions('We want our first home. Where to start?'));
assert.ok(!requestsSavingOptions('Am I on track for my home goal?'));
assert.ok(!requestsSavingOptions('Show my first home goal balance.'));
console.log('PASS citation ending shape: trusted URL, untrusted URL, unfinished body, normal punctuation, saving-options scope');
