import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
process.env.CABINET_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'customer-paths-'));
delete process.env.SUPABASE_URL;
const { db } = await import('../src/server/db.js');
const { setProvider } = await import('../src/server/llm.js');
const { abelTurn } = await import('../src/server/abel.js');
const { intentsOf } = await import('../src/server/advice/intent.js');
const { reviewedAnswer } = await import('../src/server/advice/reviewedAnswer.js');
await db.init();
let calls = 0;
setProvider({ name: 'must-not-hallucinate', isConfigured: () => true, step: async () => { calls++; throw new Error('Reviewed financial answers must not call the model'); } });
let n = 0;
async function ask(text: string, expected: RegExp, partner?: string) {
  const conversationId = `accuracy-${++n}`;
  const r = await abelTurn('lauri', conversationId, 'abel', text);
  assert.match(r.text, expected, text);
  if (partner) assert.ok(r.cards.some(c => c.type === 'offer' && c.data?.partnerId === partner), `${partner} card missing`);
  assert.ok(!r.error, JSON.stringify(r));
  console.log(`PASS ${text}`);
  return r;
}
const before = db.getCabinetEntries('lauri').length;
const goalsBefore = db.getCabinetEntries('lauri').filter(e => e.type === 'goal').length;
const asp = await ask('Rent keeps going up. We are saving for our first home. Are we too old at 31 for ASP?', /15,400/);
assert.match(asp.text, /14,600/); assert.match(asp.text, /30,000/);
await ask('How do I start investing at 26?', /18–27/);
await ask('I am finishing my degree on time. Can Kela repay some student loan?', /degree-based caps/);
await ask('We are in Finland. My mum wants to give me 7,500 euros. Is the gift tax free?', /not just the excess/);
await ask('I paid a cleaning company 600 euros, all labour. What household credit for 2026?', /reduces tax, not taxable income/);
await ask('Can I deduct my whole PS account balance in 2026?', /not the existing balance/);
await ask('My PS account is 4,200 now. Can I withdraw it in 2027?', /Today’s balance alone/);
await ask('Can you show homes that fit our deposit?', /not live listings/, 'homes');
await ask('Our electricity bill is ridiculous, can you help?', /not live market quotes/, 'energy');
await ask('We need home insurance before moving', /not guaranteed coverage/, 'insure');
await ask('We move next Friday and I have barely started packing. I need a moving company and packing help.', /nothing is booked/, 'movers');
await ask('I need a financial planner to build a money plan', /paid planning offer/, 'planner');
assert.equal(calls, 0, 'No model calls on reviewed paths');
assert.ok(!db.getCabinetEntries('lauri').some(e => e.factKey === 'helpsFamilyWithMoney'), 'Receiving a gift is not saved as helping children');
const safety = await abelTurn('lauri', 'safety-mixed', 'abel', 'Someone texted me a link asking for my codes to claim a gift');
assert.match(safety.text, /codes|scam|customer service/i);
assert.ok(!safety.cards.some(c => c.type === 'offer'), 'No offers over safety');
assert.equal(db.getCabinetEntries('lauri').filter(e => e.type === 'goal').length, goalsBefore, 'Informational questions create no goals');
// Informational gift receipt must not be persisted as helping children/grandchildren.
assert.deepEqual(intentsOf('My mum wants to give me a gift')[0]?.implies, undefined);
assert.equal(reviewedAnswer('Can I get a mortgage pre-approval?', []), null);
assert.equal(reviewedAnswer('Set up 25 every month', []), null);
assert.equal(reviewedAnswer('My Tuulikki refund has not arrived', []), null);
assert.equal(reviewedAnswer('Our electricity bill is high', []), null, 'No claim of a blocked partner card');
assert.equal(reviewedAnswer('We move next Friday', []), null, 'No claim of an unseen card');
assert.ok(db.getCabinetEntries('lauri').length >= before);
console.log('PASS action paths and blocked-card claims left unchanged');
console.log('RESULT customer-path corrections passed');
